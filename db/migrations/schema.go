package migrations

import (
	"fmt"
	"io/fs"
	"path/filepath"
	"sort"
	"strings"
)

// Schema renders the Up sections into the single schema sqlc parses; a goose Down
// section would otherwise undo its Up. TestSchemaFileIsCurrent keeps it fresh.
func Schema() ([]byte, error) {
	paths, err := fs.Glob(Files, "*.sql")
	if err != nil {
		return nil, fmt.Errorf("discover migrations: %w", err)
	}
	sort.Strings(paths)

	var out strings.Builder
	out.WriteString("-- Code generated by `just sqlc-generate` from db/migrations. DO NOT EDIT.\n")
	for _, path := range paths {
		body, err := fs.ReadFile(Files, path)
		if err != nil {
			return nil, fmt.Errorf("read migration %q: %w", path, err)
		}
		up, err := upSection(string(body))
		if err != nil {
			return nil, fmt.Errorf("%s: %w", filepath.Base(path), err)
		}
		fmt.Fprintf(&out, "\n-- %s\n%s", filepath.Base(path), up)
	}
	return []byte(out.String()), nil
}

// upSection rejects goose block directives rather than guessing, so a migration that
// needs one cannot silently lose part of its DDL.
func upSection(body string) (string, error) {
	lines := strings.Split(body, "\n")
	kept := make([]string, 0, len(lines))
	inUp := false
	sawUp := false
	for _, line := range lines {
		directive := strings.TrimSpace(line)
		switch directive {
		case "-- +goose Up":
			inUp = true
			sawUp = true
			continue
		case "-- +goose Down":
			inUp = false
			continue
		case "-- +goose StatementBegin", "-- +goose StatementEnd", "-- +goose NO TRANSACTION":
			return "", fmt.Errorf("unsupported goose directive %q", directive)
		}
		if inUp {
			kept = append(kept, line)
		}
	}
	if !sawUp {
		return "", fmt.Errorf("missing -- +goose Up")
	}
	return strings.TrimRight(strings.Join(kept, "\n"), "\n") + "\n", nil
}
